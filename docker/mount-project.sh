#!/usr/bin/env bash
# A project outside CLIKE_PROJECTS_DIR, mounted read-only for eval, gate and the /adopt baseline.
#
#   ./mount-project.sh add <folder>      # mount it (a CLike project: it has .clike/project.json)
#   ./mount-project.sh remove <folder>   # unmount it
#   ./mount-project.sh list              # the projects mounted this way
#   --no-recreate                        # only write the files; the next ./rebuild.sh applies them
#
# Only the folder itself is mounted, never a parent: the list (projects.list) and the compose
# override it generates (compose.projects.yml) are git-ignored, paths of this machine. The
# containers are recreated (about a minute) — never while an eval, kit, finalize or adopt runs.
# The VS Code extension runs it on the developer's confirmation when a project is outside.
set -euo pipefail
cd "$(dirname "$0")"
# run from VS Code (opened from the Dock): podman where Homebrew and the installers put it
export PATH="$PATH:/opt/homebrew/bin:/usr/local/bin:/opt/podman/bin:$HOME/.local/bin"

LIST=projects.list
OVERRIDE=compose.projects.yml
RECREATE=true
args=()
for a in "$@"; do
  if [ "$a" = "--no-recreate" ]; then RECREATE=false; else args+=("$a"); fi
done
set -- "${args[@]+"${args[@]}"}"

die() { echo "ERROR: $*" >&2; exit 2; }
projects_dir() { sed -n 's/^CLIKE_PROJECTS_DIR=//p' .env 2>/dev/null | tail -1; }
listed() { [ -f "$LIST" ] && grep -v '^[[:space:]]*$' "$LIST" || true; }
under() { case "$1/" in "$2"/*) return 0 ;; esac; return 1; }

write_override() {
  local roots=() p
  while IFS= read -r p; do roots+=("$p"); done < <(listed)
  if [ "${#roots[@]}" -eq 0 ]; then rm -f "$OVERRIDE"; return; fi
  local joined
  joined="$(IFS=:; echo "${roots[*]}")"
  {
    echo "# Generated by mount-project.sh — do not edit (git-ignored). Projects mounted read-only."
    echo "services:"
    for svc in gateway orchestrator eval-sandbox; do
      echo "  $svc:"
      echo "    environment:"
      echo "      - CLIKE_EVAL_ALLOWED_ROOTS=$joined"
      echo "    volumes:"
      for p in "${roots[@]}"; do echo "      - \"$p:$p:ro\""; done
    done
  } > "$OVERRIDE"
}

case "${1:-}" in
  list) listed; exit 0 ;;
  add | remove) [ -n "${2:-}" ] || die "usage: $0 $1 <folder>" ;;
  *) die "usage: $0 add|remove <folder> | list  [--no-recreate]" ;;
esac

if [ "$1" = add ]; then
  [ -d "$2" ] || die "not a folder: $2"
  dir="$(cd "$2" && pwd -P)"
  case "$dir" in *:*) die "a folder with \":\" in its path cannot be mounted: $dir" ;; esac
  [ -f "$dir/.clike/project.json" ] || die "$dir is not a CLike project (no .clike/project.json): run /init in it first"
  # a project folder, never the home, the root or a top-level folder
  [ "$dir" != "$HOME" ] && [ "$(echo "$dir" | tr -cd '/' | wc -c)" -ge 3 ] || die "$dir is too wide to mount: pick the project folder"
  base="$(projects_dir)"
  if [ -n "$base" ] && under "$dir" "$base"; then echo "$dir is already under CLIKE_PROJECTS_DIR ($base)"; exit 0; fi
  while IFS= read -r p; do
    if under "$dir" "$p"; then echo "$dir is already mounted ($p)"; exit 0; fi
  done < <(listed)
  echo "$dir" >> "$LIST"
  echo "==> mounted read-only: $dir"
else
  dir="$(cd "$2" 2>/dev/null && pwd -P || echo "$2")"
  listed | grep -vxF "$dir" > "$LIST.tmp" || true
  mv "$LIST.tmp" "$LIST"
  echo "==> unmounted: $dir"
fi
write_override

if $RECREATE; then
  ./rebuild.sh --no-build
else
  echo "==> the next ./rebuild.sh applies it"
fi
